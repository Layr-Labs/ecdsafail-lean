import argparse,json
from pathlib import Path
from capture_row_mul import capture
ROOT=Path(__file__).resolve().parents[2]
DEST=ROOT/'ECDSAAdd/Arithmetic/Paper935'
def camel(s):return ''.join(p.title() for p in s.split('_'))
def normalize(ops):
    out,bounds,i,count=[],{},0,0
    while i<len(ops):
        bounds[i]=len(out); op=ops[i]; tag=op[0]
        if tag=='HMR':
            cs=[];j=i+1
            while j<len(ops) and ops[j][0] in ('Z','CZ') and ops[j][1]==count:
                cs.append(ops[j]);bounds[j]=len(out);j+=1
            out.append(['M',op[1],cs]);count+=1;i=j
        else:
            if tag=='SWAP':
                a,b=op[1:];out.extend([['CX',b,a],['CX',a,b],['CX',b,a]])
            elif tag!='R':out.append(op)
            i+=1
    bounds[len(ops)]=len(out)
    return out,bounds

def correction(op):return '.'+op[0]+' '+' '.join('(w %d)'%q for q in op[2:])
def instr(op):
    tag=op[0]
    if tag=='M':return '.gate (.measureX (w %d) [] [%s])'%(op[1],', '.join(correction(c) for c in op[2]))
    if tag in ('Z','CZ'):return '.phaseFromRecord (_base + %d) [%s]'%(op[1],correction(op))
    return '.gate (.'+tag+' '+' '.join('(w %d)'%q for q in op[1:])+')'
def chunked(name,typ,values,params='',args='',size=96):
    chunks=[];text=[]
    for start in range(0,len(values),size):
        n=name+'Chunk'+str(start//size);chunks.append(n+args)
        text.append('private def '+n+params+' : '+typ+' := [\n  '+',\n  '.join(values[start:start+size])+'\n]\n')
    text.append('def '+name+params+' : '+typ+' :=\n  '+(' ++\n  '.join(chunks) if chunks else '[]')+'\n')
    return '\n'.join(text)
def render(data):
    files={};normalized={};align={};names=sorted(data['templates'])
    header='-- Generated by scripts/paper935/generate_row_mul.py; do not edit.\n'
    for name,ops in data['templates'].items():
        normalized[name],align[name]=normalize(ops)
        mod='HmrRowMulTemplate'+camel(name)
        text=header+'import ECDSAAdd.Framework.RecordedSyntax\n\nnamespace ECDSAAdd.Arithmetic.Paper935\n\n'
        text+=chunked('rowMul'+camel(name),'RecordedProgram',list(map(instr,normalized[name])), ' (w : Nat → Wire) (_base : Nat)',' w _base')
        text+='\nend ECDSAAdd.Arithmetic.Paper935\n'
        files[DEST/(mod+'.lean')]=text
    text=header+''.join('import ECDSAAdd.Arithmetic.Paper935.HmrRowMulTemplate'+camel(n)+'\n' for n in names)
    text+='''
namespace ECDSAAdd.Arithmetic.Paper935

/-- Lifecycle data, not a quantum instruction. Positions are relative to this
call. A release requires zero at the specified program boundary. -/
structure RowMulLifecycleEvent where
  borrow : Bool
  rawPosition : Nat
  programPosition : Nat
  measurementPosition : Nat
  wire : Wire
  deriving Repr

/-- Explicit obligation; this does not assert or establish zero or reset. -/
def RowMulReleaseZero (events : List RowMulLifecycleEvent)
    (stateAt : Nat → State) : Prop :=
  ∀ e ∈ events, e.borrow = false → (stateAt e.programPosition).basis e.wire = false

structure RowMulTemplateUse where
  template : Nat
  control : Wire
  rawStart : Nat
  programStart : Nat
  measurementStart : Nat
  deriving Repr

/-- Port 819 is the scan control. Generated tables cover every referenced port. -/
def rowMulPort (ports : Array Wire) (control : Wire) (i : Nat) : Wire :=
  if i = 819 then control else ports[i]?.getD 0

/-- The offset is the actual call's absolute source measurement ordinal. -/
def rowMulInstantiate (ports : Array Wire) (start : Nat)
    (u : RowMulTemplateUse) : RecordedProgram :=
  let w := rowMulPort ports u.control
  let base := start + u.measurementStart
  match u.template with
'''
    for i,n in enumerate(names):text+='  | '+str(i)+' => rowMul'+camel(n)+' w base\n'
    text+='  | _ => []\n\n'; summaries=[]
    for c in data['calls']:
        name=c['name'];offset=0;uses=[];events=[]
        for u in c['uses']:
            n=u['template'];ops=data['templates'][n];bounds=align[n]
            uses.append('⟨%d, %d, %d, %d, %d⟩'%(names.index(n),u['control'] or 0,u['raw_start'],offset,u['measurement_start']))
            count=0;borrows=dict(u['borrows'])
            for p,op in enumerate(ops):
                if p in borrows:events.append((True,u['raw_start']+p,offset+bounds[p],u['measurement_start']+count,c['ports'][borrows[p]]))
                if op[0]=='R':events.append((False,u['raw_start']+p,offset+bounds[p],u['measurement_start']+count,c['ports'][op[1]]))
                count+=op[0]=='HMR'
            offset+=len(normalized[n])
        assert sum(e[0] for e in events)==498 and len(events)==996
        text+='def '+name+'Ports : Array Wire := #['+', '.join(map(str,c['ports']))+']\n\n'
        text+=chunked(name+'Uses','List RowMulTemplateUse',uses)+'\n'
        text+=chunked(name+'Lifecycle','List RowMulLifecycleEvent',['⟨%s, %d, %d, %d, %d⟩'%('true' if e[0] else 'false',*e[1:]) for e in events])+'\n'
        text+='def '+name+'MeasurementStart : Nat := '+str(c['measurement_start'])+'\n\n'
        text+='def '+name+'Program : RecordedProgram :=\n  '+name+'Uses.flatMap (rowMulInstantiate '+name+'Ports '+name+'MeasurementStart)\n\n'
        summaries.append(dict(name=name,rawOperations=c['raw_count'],programInstructions=offset,measurements=c['measurement_count'],releaseEvents=498,borrowEvents=498,temporaryWire=c['ports'][818],rawStreamSha256=c['source_sha256']))
    text+='end ECDSAAdd.Arithmetic.Paper935\n'
    files[DEST/'HmrRowMulSourcePrograms.lean']=text
    manifest={k:v for k,v in data.items() if k!='templates'}
    manifest['normalization']={
        'swap': {'lowering': 'SWAP(a,b) -> CX(b,a);CX(a,b);CX(b,a)',
                 'proofs': ['rowMul_swap_lowering','rowMul_swap_directions']},
        'measurement': {'lowering': 'HMR followed immediately by same-record Z/CZ -> measureX with ordered onOne corrections',
                        'proofs': ['rowMul_record_corrections','rowMul_measure_fusion']},
        'release': 'R emits only a lifecycle event; zero before release remains a separate obligation, never reset',
        'preserved': 'Source CCX operand order and CX order unchanged; semantic comparison lemmas do not rewrite emitted data',
        'comparison_lemmas': ['rowMul_ccx_controls','rowMul_cx_same_target']}
    manifest['summary']=summaries
    files[ROOT/'scripts/paper935/row_mul_source_manifest.json']=json.dumps(manifest,indent=2,sort_keys=True)+'\n'
    return files

from source_root import pinned_source

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    try:
        source = pinned_source()
    except ValueError as exc:
        p.error(str(exc))
    files=render(capture(source))
    for path,body in files.items():
        if a.check:assert path.read_text()==body,f'Generated source mismatch: {path}'
        else:path.write_text(body)
    print(('Checked' if a.check else 'Generated'),len(files),'files from all 6,574,181 original source operations.')
if __name__=='__main__':main()
