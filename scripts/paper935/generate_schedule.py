#!/usr/bin/env python3
"""Reproduce public 935 schedule data; never infer trajectory probabilities."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'data/paper935/author-constants.json'
DEST = ROOT / 'ECDSAAdd/Arithmetic/Paper935/AuthorSchedule.lean'

def render():
    raw = SOURCE.read_bytes()
    data = json.loads(raw)
    windows = data['windows_q']
    steps = data['tstop']['S']
    columns = [windows[k] for k in ('WF', 'WG', 'WFV', 'WGV')]
    spans = data['spans_q']['reach']
    assert all(len(c) == steps for c in columns) and len(spans) == steps
    assert all(type(v) is int and v >= 0 for c in columns + [spans] for v in c)
    rows = list(zip(*columns))
    head = f'''-- Generated by scripts/paper935/generate_schedule.py. Do not edit.
-- Source SHA256: {hashlib.sha256(raw).hexdigest()}
-- Author census data are public parameters, not probability certificates.
import ECDSAAdd.Arithmetic.Paper935.WindowSchedule

namespace ECDSAAdd.Arithmetic.Paper935

set_option maxRecDepth 4096

def authorSteps : Nat := {steps}
def authorFreezeStart : Nat := {data['tstop']['Tmin']}
def authorCounterWidth : Nat := {data['z']['Wz']}
def authorHistoryCapacity : Nat := 60
def authorQcap : Nat := {data['qcap']['circuit']}

def authorWindows : List RowWindow := [
'''
    body = ',\n'.join('  ⟨'+','.join(map(str,r))+'⟩' for r in rows)
    spans_text = ','.join(map(str, spans))
    return head+body+f''']

def authorSpans : List Nat := [{spans_text}]

theorem author_lengths : authorWindows.length=533 ∧ authorSpans.length=533 := by decide

theorem author_dials : authorSteps=533 ∧ authorFreezeStart=498 ∧
    authorCounterWidth=6 ∧ authorHistoryCapacity=60 ∧ authorQcap=935 := by decide

/-- Closed finite-table bounds only; these say nothing about how often an
integer trajectory escapes the windows. -/
theorem author_exit_bounds : ∀ w∈authorWindows,
    1≤w.f ∧ 1≤w.g ∧ 1≤w.fv ∧ 1≤w.gv ∧ w.payload≤582 := by decide

theorem author_add_bounds : ∀ w∈initialWindow::authorWindows,
    w.addPad.payload≤588 := by decide

theorem author_span_bounds : ∀ n∈authorSpans,n≤59 := by decide

theorem author_lookup (t : Nat) (h : t<533) :
    ∃ w,authorWindows[t]?=some w := by
  have ht : t<authorWindows.length := by rw [author_lengths.1]; exact h
  exact ⟨authorWindows[t],by simp [ht]⟩

/-- Matches the author's lazy history allocation request. This only sizes
physical storage; it does not prove that a quantum lane's stack fits. -/
def historyRequest (reach t : Nat) : Nat := min (min reach t+1) authorHistoryCapacity

theorem historyRequest_bound (reach t : Nat) : historyRequest reach t≤60 :=
  Nat.min_le_right _ _

theorem author_before_add_bound (t : Nat) (w : RowWindow)
    (h : windowBefore authorWindows t=some w) : w.addPad.payload≤588 := by
  cases t with
  | zero =>
    simp only [windowBefore,Option.some.injEq] at h
    subst w
    exact author_add_bounds initialWindow (by simp)
  | succ t =>
    have hm : w∈authorWindows := List.mem_of_getElem? h
    exact author_add_bounds w (by simp [hm])

end ECDSAAdd.Arithmetic.Paper935
'''

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if DEST.read_text() != expected:
            raise SystemExit('Generated schedule differs; regenerate and review the diff.')
        print('Public schedule matches the pinned constants exactly.')
    else:
        DEST.write_text(expected)
