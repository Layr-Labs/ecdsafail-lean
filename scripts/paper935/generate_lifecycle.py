"""Generate actual K2/K6 gap programs; --check replays the pinned source."""
import argparse
import json
from pathlib import Path
from capture_lifecycle import capture
from generate_row_mul import chunked

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'ECDSAAdd/Arithmetic/Paper935/HmrSourceLifecyclePrograms.lean'
MANIFEST = ROOT / 'data/hmr-lifecycle.json'


def lower(ops, measurement_start):
    out, i, cursor = [], 0, measurement_start
    while i < len(ops):
        tag, *args = ops[i]
        if tag == 'SWAP':
            a, b = args
            out += [f'.gate (.CX {b} {a})', f'.gate (.CX {a} {b})', f'.gate (.CX {b} {a})']
        elif tag == 'HMR':
            corrections = []
            while i+1 < len(ops) and ops[i+1][0] in ('Z','CZ') and ops[i+1][1] == cursor:
                i += 1
                correction = ops[i]
                corrections.append('.'+correction[0]+' '+' '.join(map(str,correction[2:])))
            out.append(f'.gate (.measureX {args[0]} [] ['+', '.join(corrections)+'])')
            cursor += 1
        elif tag in ('Z', 'CZ'):
            out.append('.phaseFromRecord '+str(args[0])+' [.'+tag+' '+' '.join(map(str, args[1:]))+']')
        else:
            assert tag in ('X', 'CX', 'CCX')
            out.append('.gate (.'+tag+' '+' '.join(map(str, args))+')')
        i += 1
    return out


def render(data):
    c2, c6 = data['calls']
    a, = c2['signParts']
    assert not a['inverse'] and a['begin'] == 0
    assert c2['ops'][a['end']:] == [['HMR', q] for q in c2['y']]
    a6, b6 = c6['signParts']
    assert a6['begin'] == 0 and not a6['inverse'] and b6['inverse'] and b6['end'] == len(c6['ops'])
    fixes = c6['ops'][a6['end']:b6['begin']]
    assert len(fixes) == len(c6['out']) == 256
    assert all(op[0] == 'Z' and op[2] == q for op, q in zip(fixes, c6['out']))
    text = '-- Generated by scripts/paper935/generate_lifecycle.py; do not edit.\n'
    text += 'import ECDSAAdd.Arithmetic.Paper935.HmrLifecycleFrame\n\nnamespace ECDSAAdd.Arithmetic.Paper935\n\n'
    parts = [('s2SourceSign', c2['ops'][:a['end']], c2['measurementStart']),
             ('s6SourceSign', c6['ops'][:a6['end']], c6['measurementStart']),
             ('s6SourceCorrection', fixes, c6['measurementStart']),
             ('s6SourceUnsign', c6['ops'][b6['begin']:], c6['measurementStart']+sum(op[0]=='HMR' for op in c6['ops'][:b6['begin']]))]
    for name, ops, start in parts:
        text += chunked(name, 'RecordedProgram', lower(ops, start))+'\n'
    text += 'def s2SourceDemolished : List Wire := ['+', '.join(map(str,c2['y']))+']\n\n'
    text += 'def s2SourceGap : RecordedProgram := s2SourceSign ++ hmrDemolish s2SourceDemolished\n\n'
    text += 'def s6SourceGap : RecordedProgram := s6SourceSign ++ s6SourceCorrection ++ s6SourceUnsign\n\n'
    for c in data['calls']:
        for label,key in [('Start','measurementStart'),('End','measurementEnd')]:
            text += f'def {c["name"]}SourceGap{label} : Nat := {c[key]}\n'
    text += '\nend ECDSAAdd.Arithmetic.Paper935\n'
    data['normalization'] = {'swap': 'CX(b,a); CX(a,b); CX(b,a)',
                            'HMR': 'measureX with following corrections referring to that measurement fused in original order',
                            'Z/CZ': 'remaining phaseFromRecord at absolute source measurement ordinal'}
    data['gapCounts'] = [dict(name=c['name'], raw=len(c['ops']), normalized=len(lower(c['ops'],c['measurementStart']))) for c in data['calls']]
    return {DEST:text,MANIFEST:json.dumps(data,indent=2)+'\n'}


from source_root import pinned_source

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    try:
        source = pinned_source()
    except ValueError as exc:
        p.error(str(exc))
    files=render(capture(source))
    for path,text in files.items():
        if a.check:
            assert path.read_text()==text, f'Source lifecycle mismatch: {path}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    print('Actual s2/s6 gap programs match the complete pinned source capture.')
if __name__=='__main__':main()
